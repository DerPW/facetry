// Generates sw.js at build time: a small service worker that precaches every emitted file and
// the public assets, so the app works offline after the first visit (PWA).
import { readdirSync, statSync } from "node:fs";
import { join, relative } from "node:path";
import { createHash } from "node:crypto";
import type { Plugin } from "vite";

function publicFiles(directory: string, root = directory): string[] {
  return readdirSync(directory).flatMap((name) => {
    const path = join(directory, name);
    return statSync(path).isDirectory() ? publicFiles(path, root) : [relative(root, path)];
  });
}

const worker = (cacheName: string, assets: string[]) => `// Generated by vite/service-worker.ts
const CACHE = ${JSON.stringify(cacheName)};
const ASSETS = ${JSON.stringify(assets)};

self.addEventListener("install", (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(ASSETS)).then(() => self.skipWaiting()));
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((key) => key.startsWith("facetry-") && key !== CACHE).map((key) => caches.delete(key))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET" || new URL(request.url).origin !== location.origin) return;
  if (request.mode === "navigate") {
    // Pages: network first, so updates arrive as soon as the app is online.
    event.respondWith(fetch(request).catch(() => caches.match("./index.html")));
    return;
  }
  // Hashed assets never change: cache first.
  event.respondWith(caches.match(request).then((cached) => cached ?? fetch(request)));
});
`;

export function serviceWorker(): Plugin {
  let publicDir = "";
  return {
    name: "facetry-service-worker",
    apply: "build",
    configResolved(config) {
      publicDir = config.publicDir;
    },
    generateBundle(_options, bundle) {
      const assets = ["./", "./index.html"];
      for (const file of Object.keys(bundle)) {
        if (file !== "index.html") assets.push(`./${file}`);
      }
      for (const file of publicFiles(publicDir)) {
        assets.push(`./${file.split("\\").join("/")}`);
      }
      const version = createHash("sha256").update(assets.join("\n")).digest("hex").slice(0, 12);
      this.emitFile({
        type: "asset",
        fileName: "sw.js",
        source: worker(`facetry-${version}`, assets),
      });
    },
  };
}
